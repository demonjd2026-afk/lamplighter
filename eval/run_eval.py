"""Run every fault scenario against the real demo shop and score the response.

    python -m eval.run_eval --runs 3

Writes eval/results.json and docs/EVALUATION.md. Each run starts a fresh shop,
injects one fault, and compares what Lamplighter did with the ground truth. The
same evidence is also scored for a naive responder ("blame the latest change,
otherwise restart the service behind the edge") to show what the checks add.
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import tempfile
import time
from pathlib import Path

from eval.lab import Lab
from eval.scenarios import BY_NAME, SCENARIOS, Scenario
from lamplighter.store import TERMINAL_STATES

ROOT = Path(__file__).resolve().parents[1]


def naive_response(incident: dict | None) -> tuple[str, str] | None:
    """What 'blame the latest change, else restart' would do with the same evidence."""
    if incident is None or "bundle" not in incident["data"]:
        return None
    changes = [c for c in incident["data"]["bundle"]["facts"]["changes"]
               if c["lag_s"] >= 0 and c.get("actor") != "lamplighter" and c["kind"] in ("deploy", "config")]
    if changes:
        latest = max(changes, key=lambda c: c["ts"])
        return ("rollback_release" if latest["kind"] == "deploy" else "revert_config", latest["service"])
    return ("restart", "checkout")


def run_one(scenario: Scenario, seed: int) -> dict:
    with tempfile.TemporaryDirectory(prefix=f"eval-{scenario.name}-") as tmp:
        lab = Lab(Path(tmp), seed=seed).start()
        try:
            fault_at = scenario.inject(lab)
            if scenario.watch_s:
                time.sleep(scenario.watch_s)
                found = lab.incidents()
                incident = found[-1] if found else None
                if incident is not None and incident["state"] not in TERMINAL_STATES:
                    incident = lab.wait_closed(60)
            else:
                incident = lab.wait_closed(120)
            time.sleep(4)  # let the last requests land before measuring impact
            if incident is not None:
                incident = lab.runtime.store.get_incident(incident["id"])
            state = incident["state"] if incident else "NONE"
            data = incident["data"] if incident else {}
            diagnosis = data.get("diagnosis") or {}
            accepted = next((h for h in diagnosis.get("hypotheses", []) if h["id"] == diagnosis.get("accepted")), None)
            actions = [a for a in lab.runtime.store.actions_for(incident["id"])
                       if a["status"] == "DONE" and not a["kind"].startswith("undo:")] if incident else []
            done = [(a["kind"], a["params"]["service"]) for a in actions]
            expected = [(scenario.action, scenario.root)] if scenario.action else []
            naive = naive_response(incident)
            outcome = data.get("outcome") or {}
            impact = lab.customer_impact(fault_at)
            return {
                "scenario": scenario.name, "seed": seed, "state": state,
                "final_ok": state in scenario.final,
                "root_ok": None if scenario.root is None else bool(accepted and accepted["component"] == scenario.root),
                "cause_ok": None if scenario.cause is None else bool(accepted and accepted["cause_class"] == scenario.cause),
                "action_ok": done == expected, "wrong_actions": len([d for d in done if d not in expected]),
                "actions": done, "naive": naive,
                "naive_ok": (naive is None and not expected) or (naive is not None and [naive] == expected),
                "detect_s": outcome.get("time_to_detect_s") if incident else None,
                "impact_s": impact["impact_s"], "failed_requests": impact["failed"],
                "close_s": round(incident["closed_at"] - fault_at, 2) if incident and incident["closed_at"] else None,
                "audit_ok": lab.runtime.store.verify_audit()[0],
            }
        finally:
            lab.stop()


def _median(values: list) -> str:
    values = [v for v in values if v is not None]
    return f"{statistics.median(values):.1f}" if values else "-"


def render(results: list[dict], runs: int) -> str:
    lines = ["# Evaluation", "",
             f"Generated by `python -m eval.run_eval --runs {runs}` on {time.strftime('%Y-%m-%d', time.gmtime())}. "
             "Every run starts a fresh copy of the demo shop as real local processes, injects one fault, and lets "
             "Lamplighter respond with no model configured. Raw results are in `eval/results.json`.", "",
             "| Scenario | Runs | Correct outcome | Root cause | Cause class | Correct action | Wrong actions | "
             "Detect (s) | Customer impact (s) | Naive responder correct |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    totals = {"final_ok": 0, "action_ok": 0, "naive_ok": 0, "wrong": 0}
    for scenario in SCENARIOS:
        rows = [r for r in results if r["scenario"] == scenario.name]
        if not rows:
            continue

        def share(key: str) -> str:
            scored = [r[key] for r in rows if r[key] is not None]
            return f"{sum(scored)}/{len(scored)}" if scored else "n/a"

        totals["final_ok"] += sum(r["final_ok"] for r in rows)
        totals["action_ok"] += sum(r["action_ok"] for r in rows)
        totals["naive_ok"] += sum(r["naive_ok"] for r in rows)
        totals["wrong"] += sum(r["wrong_actions"] for r in rows)
        lines.append(f"| {scenario.title} (`{scenario.name}`) | {len(rows)} | {share('final_ok')} | {share('root_ok')} | "
                     f"{share('cause_ok')} | {share('action_ok')} | {sum(r['wrong_actions'] for r in rows)} | "
                     f"{_median([r['detect_s'] for r in rows])} | "
                     f"{_median([r['impact_s'] for r in rows]) if scenario.final != ('ESCALATED',) else 'not fixable here'} | "
                     f"{share('naive_ok')} |")
    count = len(results)
    lines += ["",
              f"**Totals over {count} runs:** correct outcome {totals['final_ok']}/{count}, correct action (including "
              f"correctly taking none) {totals['action_ok']}/{count}, wrong actions {totals['wrong']}, audit chain intact "
              f"{sum(r['audit_ok'] for r in results)}/{count}. The naive responder would have chosen correctly in "
              f"{totals['naive_ok']}/{count}.", "",
              "## How to read this", "",
              "- **Correct outcome** is the expected final state: RESOLVED where an automated fix exists, ESCALATED where "
              "a human must decide, and no incident or SELF_RESOLVED where nothing should be done.",
              "- **Detect** is the time from the first failed customer request to the incident opening. **Customer "
              "impact** is the time from the fault to the last failed customer request, measured at the edge.",
              "- **Naive responder** is scored on its decision only (it is not executed): roll back or revert the most "
              "recent change before the failure, otherwise restart the service behind the edge.",
              "", "## Limits of this evaluation", "",
              "- The windows are scaled down to seconds (the `demo` timing profile). Production defaults use 5 minute "
              "and 1 hour windows and a 2 minute hold, so real response times are minutes, not seconds.",
              "- Eight scenarios on one small system. They were written alongside the diagnosis rules, so this "
              "measures that the system does what it is designed to do, not how it generalises to unseen systems.",
              "- One fault at a time. Overlapping faults are expected to end in ESCALATED, and are not measured here.",
              "- For the two scenarios that end in ESCALATED the fault is still present when the run stops, so no "
              "customer-impact time is reported. `restart_ineffective` escalates only after the restart fails its "
              "proof, about 40 seconds after the action in this timing profile.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--only", nargs="*", default=None, help="scenario names")
    parser.add_argument("--render-only", action="store_true", help="rebuild docs/EVALUATION.md from eval/results.json")
    args = parser.parse_args(argv)
    if args.render_only:
        results = json.loads((ROOT / "eval" / "results.json").read_text(encoding="utf-8"))
        runs = max(sum(1 for r in results if r["scenario"] == s.name) for s in SCENARIOS)
        (ROOT / "docs" / "EVALUATION.md").write_text(render(results, runs), encoding="utf-8")
        return 0
    chosen = [BY_NAME[name] for name in args.only] if args.only else SCENARIOS
    results = []
    for run in range(args.runs):
        for scenario in chosen:
            result = run_one(scenario, seed=101 + run)
            results.append(result)
            print(json.dumps(result), flush=True)
    (ROOT / "eval" / "results.json").write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")
    if not args.only:
        (ROOT / "docs" / "EVALUATION.md").write_text(render(results, args.runs), encoding="utf-8")
    failed = [r for r in results if not (r["final_ok"] and r["action_ok"])]
    print(f"{len(results) - len(failed)}/{len(results)} runs correct", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
